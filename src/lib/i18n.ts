/** Only built-in category labels are localized; user-created names stay exact. */
export function translateCategory(locale: AppLocale, name: string): string {
  return CATEGORY_TRANSLATIONS[locale][name] ?? name;
}

export function localizedCurrencyLabel(locale: AppLocale, currency: string): string {
  if (currency !== "UZS") return currency;
  if (locale === "ru") return "сум";
  if (locale === "uz-Cyrl") return "сўм";
  return "so‘m";
}

function intlLocale(locale: AppLocale): string {
  return locale === "ru" ? "ru-RU" : locale === "uz-Cyrl" ? "uz-Cyrl-UZ" : "uz-Latn-UZ";
}

export function localizedMonth(locale: AppLocale, month: string): string {
  const match = month.match(/^(\d{4})-(\d{2})$/);
  if (!match) return month;
  const date = new Date(Date.UTC(Number(match[1]), Number(match[2]) - 1, 1));
  const formatted = new Intl.DateTimeFormat(intlLocale(locale), {
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(date);
  return formatted.charAt(0).toLocaleUpperCase(intlLocale(locale)) + formatted.slice(1);
}
