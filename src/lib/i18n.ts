/**
 * Older rows use `uz`; Telegram sends short BCP-47-like codes (`uz`, `ru`).
 * Keep normalization at the boundary so the rest of the app only sees one of
 * the three product locales.
 */
export function normalizeLocale(value: unknown): AppLocale {
  const raw = typeof value === "string" ? value.trim().toLowerCase().replace("_", "-") : "";
  if (raw === "ru" || raw.startsWith("ru-")) return "ru";
  if (raw === "uz-cyrl" || raw.startsWith("uz-cyrl-")) return "uz-Cyrl";
  if (raw === "uz-latn" || raw === "uz" || raw.startsWith("uz-latn-")) return "uz-Latn";
  return DEFAULT_LOCALE;
}

